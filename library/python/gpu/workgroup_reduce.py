"""float64 reference of library/wgsl/workgroup_reduce.wgsl (sum / max / min / max-abs of an array).

The function :func:`reduce` follows the WGSL algorithm step by step (block of 1024 elements per workgroup, four
elements per thread 256 apart, shared-memory tree, then one workgroup that strides over the partials), but in
float64.  Order matters only for the sum; max/min/max|x| are order-free and exact.

Units: the result has the units of the input values.
Precision of the GPU kernel (f32): compare sums with a tolerance relative to ``sum(|x|)`` (see
:func:`sum_tolerance`), never relative to ``|sum(x)|``.

Test inputs are generated by :func:`hash_values`, an integer hash that the JS test re-implements bit for bit, so
the 1e7-element hard case does not have to be stored: only the exact results are.  Every generated value is an
integer of at most 24 bits times a power of two, hence exactly representable in float32 and float64.
"""
import math

import numpy as np

WG = 256
PER_THREAD = 4
BLOCK = WG * PER_THREAD
OPS = ("sum", "max", "min", "maxabs")
F32_MAX = 3.4028234e38


def _identity(op):
    return {"sum": 0.0, "max": -F32_MAX, "min": F32_MAX, "maxabs": 0.0}[op]


def _combine(a, b, op):
    if op == "sum":
        return a + b
    if op == "min":
        return np.minimum(a, b)
    return np.maximum(a, b)


def _tree(v, op):
    """Tree reduction over the last axis (length 256): v[i] = v[i] (+) v[i + s], s = 128, 64, ..., 1."""
    s = v.shape[-1] // 2
    while s > 0:
        v = _combine(v[..., :s], v[..., s:2 * s], op)
        s //= 2
    return v[..., 0]


def reduce(x, op="sum"):
    """Two-pass reduction of a 1D array ``x`` (any length >= 1) to a Python float.

    op: "sum" | "max" | "min" | "maxabs".  Mirrors reduce_partial + reduce_final of the WGSL kernel.
    """
    if op not in OPS:
        raise ValueError(f"op must be one of {OPS}")
    x = np.asarray(x, dtype=np.float64).ravel()
    n = x.size
    if n < 1:
        raise ValueError("n must be >= 1")
    if op == "maxabs":
        x = np.abs(x)
    ident = _identity(op)
    nparts = -(-n // BLOCK)
    pad = np.full(nparts * BLOCK, ident)
    pad[:n] = x
    # element index within a block = k * 256 + lid  ->  axes (workgroup, k, lid)
    blocks = pad.reshape(nparts, PER_THREAD, WG)
    acc = np.full((nparts, WG), ident)
    for k in range(PER_THREAD):                       # sequential per thread
        acc = _combine(acc, blocks[:, k, :], op)
    partial = _tree(acc, op)                           # one value per workgroup
    # reduce_final: thread lid handles partials lid, lid + 256, ...
    nrows = -(-nparts // WG)
    pp = np.full(nrows * WG, ident)
    pp[:nparts] = partial
    pp = pp.reshape(nrows, WG)
    acc = np.full(WG, ident)
    for r in range(nrows):
        acc = _combine(acc, pp[r], op)
    return float(_tree(acc, op))


def sum_tolerance(n, sum_abs, rtol_unit=2.0 ** -24):
    """Rigorous f32 bound  (4 + 8 + ceil(nparts/256) + 8) * 2^-24 * sum|x|  on |GPU sum - exact sum|."""
    nparts = -(-n // BLOCK)
    return (4 + 8 + -(-nparts // WG) + 8) * rtol_unit * sum_abs


def hash_values(n, seed=0, emin=-20, emax=20, bias=0):
    """Deterministic mixed-sign, wide-dynamic-range test data (float64 array, all values exact in float32).

    h = fmix32(i * 2654435761 + seed) (murmur3 finaliser, uint32 arithmetic);
    m = (h & 0xFFFFFF) - 2^23 + bias  (signed integer, |m| < 2^24);  e = (h >> 24) % (emax - emin + 1) + emin;
    value = m * 2^(e - 10).
    """
    i = np.arange(n, dtype=np.uint32)
    h = i * np.uint32(2654435761) + np.uint32(seed)
    h ^= h >> np.uint32(16)
    h *= np.uint32(0x85EBCA6B)
    h ^= h >> np.uint32(13)
    h *= np.uint32(0xC2B2AE35)
    h ^= h >> np.uint32(16)
    m = (h & np.uint32(0xFFFFFF)).astype(np.int64) - (1 << 23) + bias
    e = ((h >> np.uint32(24)).astype(np.int64) % (emax - emin + 1)) + emin
    return m.astype(np.float64) * np.exp2((e - 10).astype(np.float64))


def exact_stats(x):
    """Independent results: math.fsum (exactly rounded sum), numpy max/min."""
    x = np.asarray(x, dtype=np.float64)
    return {"sum": math.fsum(x.tolist()), "sum_abs": math.fsum(np.abs(x).tolist()),
            "max": float(x.max()), "min": float(x.min()), "maxabs": float(np.abs(x).max())}


# (name, n, seed, bias, emin, emax, maxGroupsX or 0 for device default)
CASES = [
    ("n=1", 1, 1, 0, -20, 20, 0),
    ("n=1000 (partial block)", 1000, 2, 0, -20, 20, 0),
    ("n=1025 (one element in 2nd block)", 1025, 3, 0, -20, 20, 0),
    ("n=300001, 2D dispatch (maxGroupsX=64)", 300001, 4, 0, -20, 20, 64),
    ("n=2e5 all negative (max identity)", 200000, 5, -(1 << 23), 0, 0, 0),
    ("n=1e7 mixed sign, 2^40 dynamic range", 10_000_000, 6, 0, -20, 20, 0),
]


def make_reference():
    out = {"hash": "fmix32(i*2654435761+seed); m=(h&0xFFFFFF)-2^23+bias; e=(h>>24)%(emax-emin+1)+emin; v=m*2^(e-10)",
           "cases": []}
    for name, n, seed, bias, emin, emax, mg in CASES:
        x = hash_values(n, seed, emin, emax, bias)
        st = exact_stats(x)
        out["cases"].append({"name": name, "n": n, "seed": seed, "bias": bias, "emin": emin, "emax": emax,
                             "maxGroupsX": mg, **st})
    return out
